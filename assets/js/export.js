// CSV and Markdown builders (PLAN §5 Flow C step 4, test 16). Pure string functions plus
// two small browser helpers (download/copy) that are only called from app.js.

export const CSV_COLUMNS = [
  'section', 'term', 'n', 'union_count', 'competitors', 'your_count',
  'per_competitor', 'in_heading', 'action', 'notes',
];

export function csvField(value) {
  const s = value == null ? '' : String(value);
  if (/[",\r\n]/.test(s)) return '"' + s.replace(/"/g, '""') + '"';
  return s;
}

export function csvLine(values) {
  return values.map(csvField).join(',');
}

function levelsLabel(levels) {
  return (levels || []).map((l) => 'h' + l).join(' ');
}

function headingNotes(h) {
  const parts = [];
  if (h.variants && h.variants.length) parts.push('variants: ' + h.variants.join(' | '));
  if (h.yourClosest && h.yourClosest.text) parts.push(`your closest: ${h.yourClosest.text} (${h.yourClosest.sim})`);
  return parts.join('; ');
}

// Rows for the unified CSV. gaps: GapRow[]; headingGaps: topic[]; entityGaps: entity[].
export function exportRows({ gaps = [], headingGaps = [], entityGaps = [] }) {
  const rows = [];
  for (const g of gaps) {
    rows.push([
      'gap phrase', g.term, g.n, g.unionCount, `${g.cov}/${g.K}`, g.yourCount ?? 0,
      g.perCompetitor.join('|'), g.inHeading ? 'h' + g.inHeading : '', g.action,
      g.subsumes && g.subsumes.length ? 'also: ' + g.subsumes.join(', ') : '',
    ]);
  }
  for (const h of headingGaps) {
    rows.push([
      'heading gap', h.heading, '', '', `${h.covH}/${h.K}`, '', '', levelsLabel(h.levels),
      'Consider a section', headingNotes(h),
    ]);
  }
  for (const e of entityGaps) {
    rows.push([
      'entity gap', e.surface, '', e.unionCount, `${e.cov}/${e.K}`, 0, e.perCompetitor.join('|'), '',
      'Mention by name', e.source === 'curated' ? 'curated list' : 'capitalized sequence',
    ]);
  }
  return rows;
}

export function toCSV(sections) {
  const lines = [csvLine(CSV_COLUMNS), ...exportRows(sections).map(csvLine)];
  return '\uFEFF' + lines.join('\r\n') + '\r\n';
}

export function mdCell(value) {
  return String(value == null ? '' : value).replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

export function mdTable(headers, rows) {
  const out = ['| ' + headers.map(mdCell).join(' | ') + ' |', '|' + headers.map(() => ' --- ').join('|') + '|'];
  for (const r of rows) out.push('| ' + r.map(mdCell).join(' | ') + ' |');
  return out.join('\n');
}

export function toMarkdown({ gaps = [], headingGaps = [], entityGaps = [], meta = {} }) {
  const labels = meta.competitorLabels || [];
  const parts = [];
  parts.push(`# Page Content Gap report${meta.yourLabel ? ` — ${meta.yourLabel}` : ''}`);
  if (labels.length) parts.push(`Competitors: ${labels.join(', ')}`);
  if (meta.date) parts.push(`Generated: ${meta.date}`);
  parts.push('');

  parts.push(`## Gap phrases (${gaps.length})`);
  parts.push(
    mdTable(
      ['Phrase', 'n', 'Union', 'Competitors', ...labels.map((l) => l), 'In heading', 'Suggested action'],
      gaps.map((g) => [
        g.term, g.n, g.unionCount, `${g.cov}/${g.K}`, ...g.perCompetitor.map((c) => c),
        g.inHeading ? 'h' + g.inHeading : '', g.action,
      ]),
    ),
  );
  parts.push('');

  parts.push(`## Heading gaps (${headingGaps.length})`);
  parts.push(
    mdTable(
      ['Heading', 'Competitors', 'Levels', 'Variants', 'Your closest', 'Sim'],
      headingGaps.map((h) => [
        h.heading, `${h.covH}/${h.K}`, levelsLabel(h.levels), (h.variants || []).join('; '),
        h.yourClosest ? h.yourClosest.text : '', h.yourClosest ? h.yourClosest.sim : '',
      ]),
    ),
  );
  parts.push('');

  parts.push(`## Entities (heuristic) (${entityGaps.length})`);
  parts.push(
    mdTable(
      ['Entity', 'Union', 'Competitors', ...labels.map((l) => l), 'Source'],
      entityGaps.map((e) => [
        e.surface, e.unionCount, `${e.cov}/${e.K}`, ...e.perCompetitor.map((c) => c),
        e.source === 'curated' ? 'curated list' : 'capitalized',
      ]),
    ),
  );
  parts.push('');
  parts.push('_Generated by Page Content Gap. On-page text comparison only; not a ranking guarantee._');
  return parts.join('\n') + '\n';
}

// Browser helpers (no-ops outside a DOM).
export function downloadText(filename, text, mime = 'text/plain;charset=utf-8') {
  if (typeof document === 'undefined') return;
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export async function copyText(text) {
  if (typeof navigator !== 'undefined' && navigator.clipboard && navigator.clipboard.writeText) {
    await navigator.clipboard.writeText(text);
    return true;
  }
  if (typeof document === 'undefined') return false;
  const ta = document.createElement('textarea');
  ta.value = text;
  ta.setAttribute('readonly', '');
  ta.style.position = 'fixed';
  ta.style.left = '-9999px';
  document.body.appendChild(ta);
  ta.select();
  let ok = false;
  try { ok = document.execCommand('copy'); } catch { ok = false; }
  ta.remove();
  return ok;
}
